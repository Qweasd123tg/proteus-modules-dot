fn id(i: usize) -> String {
    format!("thread-{:08x}-{:04x}-{:04x}", i / 100, i % 100, i % 13)
}
fn item(i: usize, revised: bool) -> Summary {
    Summary {
        id: id(i),
        cwd: format!("/projects/{}", i % 20).into(),
        title: format!("Session {i} ({revised})"),
        parent_thread_id: (i % 4 == 3).then(|| id(i - 3)),
        updated_at: i as i64 + if revised { 10000 } else { 0 },
        ..Summary::default()
    }
}
struct WorkspaceFields {
    sessions: Vec<ConversationSummary>,
    deleting_sessions: HashSet<ChatKey>,
}

fn merge(this: &mut WorkspaceFields, page: agents::codex::Page<Summary>) {
    // Generated by verify.sh: the merge statements from the real UI callback.
    include!("page_merge.inc");
}
fn digest(rows: &[ConversationSummary]) -> u64 {
    let mut h = DefaultHasher::new();
    for row in rows {
        row.key.hash(&mut h);
        row.preview.hash(&mut h);
        row.parent.hash(&mut h);
        row.updated_at_ms.hash(&mut h);
    }
    h.finish()
}
fn main() {
    let arm = std::env::args().nth(1).unwrap_or_default();
    for (name, n, start, width) in [
        ("small", 32, 8, 16),
        ("front", 4096, 0, 50),
        ("tail", 4096, 4046, 50),
        ("new", 4096, 4096, 50),
        ("single-tail", 4096, 4095, 1),
        ("tail-four", 4096, 4092, 4),
        ("tail-five", 4096, 4091, 5),
        ("tail-eight", 4096, 4088, 8),
        ("tail-nine", 4096, 4087, 9),
        ("empty", 4096, 0, 0),
    ] {
        let original: Vec<_> = (0..n).map(|i| from_codex(&item(i, false))).collect();
        let page: Vec<_> = (start..start + width).map(|i| item(i, true)).collect();
        let mut times = Vec::new();
        let mut checksum = None;
        for _ in 0..22 {
            let mut workspace = WorkspaceFields {
                sessions: original.clone(),
                deleting_sessions: HashSet::new(),
            };
            let batch = agents::codex::Page {
                data: page.clone(),
                next_cursor: None,
            };
            let begin = Instant::now();
            merge(black_box(&mut workspace), black_box(batch));
            times.push(begin.elapsed().as_nanos());
            let hash = digest(black_box(&workspace.sessions));
            assert_eq!(checksum.get_or_insert(hash), &hash);
        }
        times.remove(0);
        times.sort_unstable();
        println!(
            "{arm}\t{name}\t{n}\t{width}\t{}\t{}",
            checksum.unwrap(),
            times[times.len() / 2]
        );
    }
}
